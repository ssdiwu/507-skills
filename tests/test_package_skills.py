 def test_build_refuses_bad_sources_and_preserves_existing_delivery(self):
  output=Path(self.tmp.name)/'delivery'
  bundle=Path(self.call('build',extra=['--output',output])['path']);before=pack.file_map(bundle)
  manifest_path=self.root/'skills/507-demo/RESOURCES.md';original=manifest_path.read_bytes()
  for case in ['private-code','marked-copy','unmarked-copy','missing-dependency']:
   with self.subTest(case=case):
    target=self.root/'skills/507-demo/references/reintroduced.md';removed=None
    if case=='missing-dependency':
     target=self.root/'lib/components/visual-runtime/visuals/Artifact.tsx';removed=target.read_bytes();target.unlink()
    else:
     rel='references/reintroduced.md'
     if case=='private-code':rel='references/reintroduced.tsx';target=self.root/'skills/507-demo'/rel;raw=b'export default null'
     elif case=='marked-copy':raw=b'<!-- Generated by 507 package_skills; source=lib/example.md -->'
     else:raw=(self.root/'lib/methods/evidence.md').read_bytes()
     target.write_bytes(raw)
     self.resource('507-demo',lambda d:d['files'].append(rel))
    try:
     failure=self.call('build',ok=False,extra=['--output',output]);self.assertEqual(failure['status'],'FAIL')
     expected={'private-code':'private executable/component/runtime','marked-copy':'copied shared resource','unmarked-copy':'verbatim shared text','missing-dependency':'Missing file'}
     self.assertIn(expected[case],failure['error'])
     self.assertEqual({p.name for p in output.iterdir()},{bundle.name})
     self.assertEqual(pack.file_map(bundle),before)
    finally:
     if removed is not None:target.write_bytes(removed)
     else:target.unlink()
     manifest_path.write_bytes(original)
