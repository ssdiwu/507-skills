"""Enforce direct shared dependencies, no private copies and safe immutable collections.

The user replaced per-skill self-contained copies with one explicit shared core.
The former copy/sync rollback tests are superseded by no-copy and read-only
collection checks; path, identity, source integrity and output protection remain.
"""
