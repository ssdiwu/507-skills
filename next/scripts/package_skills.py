def check_skill_index(root):
    """Compare the generated name index to current declarations, never host state."""
    spec = importlib.util.spec_from_file_location('library_view_for_packages', within(root, 'lib/components/library_view.py', True))
    library = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(library)
    actual, _ = library.read_index(within(root, 'lib/registry/skill-entry-index.md', True))
    view = library.project(root, within(root, 'next/packages.json', True),
                           within(root, 'lib/catalog.json', True), within(root, DISPOSITIONS, True))
    if actual != library.skill_index(view):
        raise PackageError('Stale skill-entry index; regenerate from current source declarations')

class PackageError(ValueError):
    pass

def digest(data):
    return hashlib.sha256(data).hexdigest()

def rename_new(source, destination):
    """Publish a complete directory while refusing any concurrent destination."""
    if os.name == 'nt':
        os.rename(source, destination)  # Windows rename refuses an existing destination.
        return
    libc = ctypes.CDLL(None, use_errno=True)
    if sys.platform == 'darwin':
        call = libc.renamex_np
        call.argtypes = [ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint]
        result = call(os.fsencode(source), os.fsencode(destination), 4)  # RENAME_EXCL
    elif sys.platform.startswith('linux') and hasattr(libc, 'renameat2'):
        call = libc.renameat2
        call.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
        result = call(-100, os.fsencode(source), -100, os.fsencode(destination), 1)  # RENAME_NOREPLACE
    else:
        raise PackageError('Exclusive directory publication unavailable on this platform')
    if result:
        err = ctypes.get_errno()
        raise OSError(err, os.strerror(err), str(destination))

def relative(value):
    if not isinstance(value, str) or not value or '\\' in value:
        raise PackageError('Expected a nonempty POSIX relative path')
    p = PurePosixPath(value)
    if p.is_absolute() or '..' in p.parts or '.' == value:
        raise PackageError(f'Unsafe relative path: {value}')
    return p

def within(root, value, require=False):
    rel = relative(value)
    path = root.joinpath(*rel.parts)
    cursor = root
    for part in rel.parts:
        cursor /= part
        if cursor.is_symlink():
            raise PackageError(f'Symlink not allowed: {value}')
    if not path.resolve().is_relative_to(root.resolve()):
        raise PackageError(f'Path escapes root: {value}')
    if require and not path.is_file():
        raise PackageError(f'Missing file: {value}')
    return path

def load_manifest(root):
    path = within(root, 'next/packages.json', True)
    try:
        config = json.loads(path.read_text())
    except (ValueError, UnicodeError) as exc:
        raise PackageError(f'Invalid package manifest: {exc}') from exc
    if not isinstance(config, dict) or config.get('schema') != 1 or config.get('system') != '507-layered-capabilities':
        raise PackageError('Unsupported package manifest')
    entries = config.get('skills')
    if not isinstance(entries, list) or not all(isinstance(e, dict) and isinstance(e.get('name'), str) for e in entries) or {e.get('name') for e in entries} != SKILL_NAMES or len(entries) != len(SKILL_NAMES):
        raise PackageError('This delivery must contain exactly the declared current skill identities')
    skills_root = within(root, 'next/skills')
    if not skills_root.is_dir() or {p.name for p in skills_root.iterdir()} != SKILL_NAMES:
        raise PackageError('Skill source directory has undeclared entries')
    for entry in entries:
        name = entry['name']
        if entry.get('source') != f'next/skills/{name}':
            raise PackageError(f'Unexpected source for {name}')
        base = within(root, entry['source'])
        if not base.is_dir():
            raise PackageError(f'Missing skill directory: {name}')
        files = entry.get('files')
        if not isinstance(files, list) or not all(isinstance(f, str) for f in files) or len(files) != len(set(files)) or not {'SKILL.md', 'agents/openai.yaml'} <= set(files):
            raise PackageError(f'Missing or duplicate declared files: {name}')
        for file in files:
            relative(file)
            if file.startswith('references/shared/'):
                raise PackageError('Shared copies belong in the shared manifest section')
            within(base, file, True)
        targets = set()
        if not isinstance(entry.get('shared'), list):
            raise PackageError(f'Missing shared resource list: {name}')
        for item in entry['shared']:
            if not isinstance(item, dict):
                raise PackageError(f'Invalid shared resource: {name}')
            src, dest = item.get('source'), item.get('target')
            relative(src); relative(dest)
            method = src.startswith('lib/methods/') and src.endswith('.md') and dest.startswith('references/shared/') and dest.endswith('.md')
            component = name in COMPONENT_CONSUMERS.get(src, set()) and COMPONENTS.get(src) == dest
            resource_doc = name in SHARED_DOC_CONSUMERS.get(src, set()) and SHARED_DOCS.get(src) == dest
            if not method and not component and not resource_doc:
                raise PackageError(f'Unsupported shared source/target: {src} -> {dest}')
            if dest in targets or dest in files:
                raise PackageError(f'Invalid or duplicate shared target: {dest}')
            targets.add(dest)
            within(root, src, True); within(base, dest)
        undeclared = set(file_map(base)) - set(files) - targets
        if undeclared:
            raise PackageError(f'{name}: undeclared package files: {sorted(undeclared)}')
    return entries

def expected_copy(root, source):
    raw = within(root, source, True).read_bytes()
    if source in COMPONENTS:
        marker = PY_MARKER + f'source={source}; sha256={digest(raw)}; edit source only\n\n'.encode()
        if raw.startswith(b'#!'):
            first, rest = raw.split(b'\n', 1)
            return first + b'\n' + marker + rest
        return marker + raw
    return MARKER + f'source={source}; sha256={digest(raw)}; edit source only -->\n\n'.encode() + raw

def managed_copy(raw, source):
    if source in COMPONENTS:
        first, _, rest = raw.partition(b'\n')
        return (rest if first.startswith(b'#!') else raw).startswith(PY_MARKER)
    return raw.startswith(MARKER)

def file_map(base):
    result = {}
    for path in sorted(base.rglob('*')):
        rel = path.relative_to(base).as_posix()
        within(base, rel)
        if path.is_file():
            result[rel] = path.read_bytes()
    return result

def yaml_text_scalar(raw):
    if raw.startswith('"'):
        value = json.loads(raw)
        if not isinstance(value, str):
            raise PackageError('Metadata value must be a string')
        return value
    if raw.startswith("'") and raw.endswith("'"):
        return raw[1:-1].replace("''", "'")
    return raw.strip()

def validate_package(base, name):
    payload = file_map(base)
    unexpected = [rel for rel in payload if rel not in ('SKILL.md', 'agents/openai.yaml')
                  and not (rel.startswith('references/') and rel.endswith('.md'))
                  and not any(name in COMPONENT_CONSUMERS[src] and rel == target for src, target in COMPONENTS.items())]
    if unexpected:
        raise PackageError(f'{name}: unexpected package files: {unexpected}')
    if 'SKILL.md' not in payload:
        raise PackageError(f'{name}: missing SKILL.md')
    text = payload['SKILL.md'].decode('utf-8')
    match = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if not match:
        raise PackageError(f'{name}: invalid frontmatter')
    fields = {}
    for line in match.group(1).splitlines():
        if ':' in line:
            key, value = line.split(':', 1)
            fields[key] = yaml_text_scalar(value.strip())
    if fields.get('name') != name or not fields.get('description'):
        raise PackageError(f'{name}: wrong identity or empty description')
    meta = payload.get('agents/openai.yaml', b'').decode('utf-8')
    if not meta.startswith('interface:\n'):
        raise PackageError(f'{name}: missing interface metadata')
    metadata = {}
    for key in ('display_name', 'short_description', 'default_prompt'):
        found = re.search(r'^  '+key+r':\s*(.+)$', meta, re.M)
        if not found:
            raise PackageError(f'{name}: missing {key}')
        metadata[key] = yaml_text_scalar(found.group(1))
        if not metadata[key]:
            raise PackageError(f'{name}: empty {key}')
    if '$'+name not in metadata['default_prompt']:
        raise PackageError(f'{name}: prompt points to a different skill')
    for rel, raw in payload.items():
        if rel.endswith('.py'):
            try:
                compile(raw, str(base/rel), 'exec')
            except SyntaxError as exc:
                raise PackageError(f'{name}/{rel}: invalid Python syntax: {exc}') from exc
        if rel.endswith('/SKILL.md'):
            raise PackageError(f'{name}: unexpected nested skill entry {rel}')
        if not rel.endswith('.md'):
            continue
        for target in re.findall(r'\[[^\]]*\]\(([^)]+)\)', raw.decode('utf-8')):
            target = target.strip('<>')
            parsed = urlsplit(target)
            if parsed.scheme in ('http', 'https', 'mailto') or target.startswith('#'):
                continue
            if parsed.scheme or target.startswith('/'):
                raise PackageError(f'{name}/{rel}: absolute or unsupported reference {target}')
            dest = (base/rel).parent/unquote(parsed.path)
            if not dest.resolve().is_relative_to(base.resolve()):
                raise PackageError(f'{name}/{rel}: reference escapes package: {target}')
            local = dest.resolve().relative_to(base.resolve()).as_posix()
            within(base, local, True)
    return payload

def check(root, entries=None):
    entries = entries or load_manifest(root)
    payload = {}
    for entry in entries:
        base = within(root, entry['source'])
        expected_targets = {item['target'] for item in entry['shared']}
        shared_base = base/'references/shared'
        existing = {p.relative_to(base).as_posix() for p in shared_base.rglob('*') if p.is_file()} if shared_base.exists() else set()
        if existing - expected_targets:
            raise PackageError(f'{entry["name"]}: unlisted shared files: {sorted(existing - expected_targets)}')
        for item in entry['shared']:
            target = within(base, item['target'], True)
            if target.read_bytes() != expected_copy(root, item['source']):
                raise PackageError(f'{entry["name"]}: shared copy drift: {item["target"]}')
        payload[entry['name']] = validate_package(base, entry['name'])
        expected_files = set(entry['files']) | expected_targets
        if set(payload[entry['name']]) != expected_files:
            raise PackageError(f'{entry["name"]}: declared package file set differs')
    check_skill_index(root)
    return payload

def sync(root):
    entries = load_manifest(root)
    skills_root = within(root, 'next/skills')
    original = file_map(skills_root)
    inputs = {'next/packages.json': (root/'next/packages.json').read_bytes()}
    copies = {}
    for entry in entries:
        base = within(root, entry['source'])
        for item in entry['shared']:
            path = within(base, item['target'])
            if path.exists() and (not path.is_file() or not managed_copy(path.read_bytes(), item['source'])):
                raise PackageError(f'Refusing to overwrite an unmanaged file: {item["target"]}')
            inputs[item['source']] = within(root, item['source'], True).read_bytes()
            copies[entry['name']+'/'+item['target']] = expected_copy(root, item['source'])
    candidate_files = {**original, **copies}
    stage = Path(tempfile.mkdtemp(prefix='.skill-sync-', dir=root/'next'))
    candidate = stage/'candidate-skills'
    backup = stage/'previous-skills'
    preserve_recovery = False
    committed = False
    try:
        for rel, raw in candidate_files.items():
            path = within(candidate, rel)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
        for entry in entries:
            payload = validate_package(candidate/entry['name'], entry['name'])
            expected = set(entry['files']) | {x['target'] for x in entry['shared']}
            if set(payload) != expected:
                raise PackageError('Staged package differs from declared files')
        # Check the complete candidate before touching either usable source package.
        if file_map(skills_root) != original or any(within(root, rel, True).read_bytes() != raw for rel, raw in inputs.items()):
            raise PackageError('Inputs changed during sync; current packages preserved')
        if candidate_files == original:
            return check(root, entries)
        skills_root.rename(backup)
        candidate.rename(skills_root)
        result = check(root, entries)
        committed = True
        return result
    except BaseException as error:
        # A rename may take effect before Python delivers an interruption.
        # Filesystem state, not a subsequent flag assignment, owns recovery.
        if backup.exists():
            try:
                if skills_root.exists():
                    skills_root.rename(stage/'failed-candidate')
                backup.rename(skills_root)
            except BaseException as recovery_error:
                preserve_recovery = True
                raise PackageError(f'Sync failed; recovery retained at {stage}: {recovery_error}') from error
        raise
    finally:
        if backup.exists() and not committed:
            preserve_recovery = True
        if not preserve_recovery and stage.exists():
            shutil.rmtree(stage)

def build(root, output=None):
    payload = check(root)
    records = {f'{name}/{rel}': digest(raw) for name, files in payload.items() for rel, raw in files.items()}
    fingerprint = digest(json.dumps(records, sort_keys=True, separators=(',', ':')).encode())
    manifest = {'schema':1, 'system':'507-layered-capabilities', 'fingerprint':fingerprint, 'files':records}
    manifest_raw = (json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True)+'\n').encode()
    output = Path(output).absolute() if output else root/'next/dist'
    if output.is_symlink(): raise PackageError('Build output must not be a symlink')
    output = output.resolve()
    forbidden = [root/'lib', root/'next/skills', root/'next/scripts', root/'next/tests']
    if output == root or root.is_relative_to(output) or any(output.is_relative_to(p) for p in forbidden):
        raise PackageError('Build output overlaps source or repository parent')
    output.mkdir(parents=True, exist_ok=True)
    if output.is_symlink(): raise PackageError('Build output must not be a symlink')
    final = output/fingerprint
    expected = {**{f'{name}/{rel}':raw for name, files in payload.items() for rel, raw in files.items()}, 'bundle.json':manifest_raw}
    if final.exists() or final.is_symlink():
        if final.is_symlink() or not final.is_dir() or file_map(final) != expected:
            raise PackageError('Existing immutable bundle differs; preserved without overwrite')
        return final, manifest
    stage = Path(tempfile.mkdtemp(prefix='.candidate-', dir=output))
    try:
        for rel, raw in expected.items():
            path = within(stage, rel);path.parent.mkdir(parents=True, exist_ok=True);path.write_bytes(raw)
        for name in payload: validate_package(stage/name, name)
        if file_map(stage) != expected: raise PackageError('Staged bundle differs')
        # Never replace an existing bundle. A racing writer is detected by rename.
        rename_new(stage, final)
    finally:
        if stage.exists(): shutil.rmtree(stage)
    return final, manifest

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['sync', 'check', 'build'])
    parser.add_argument('--root', type=Path, default=DEFAULT_ROOT, help='Repository root; useful for isolated validation')
    parser.add_argument('--output', type=Path, help='Build destination; immutable fingerprint subdirectory is created')
    args = parser.parse_args(argv)
    if args.output and args.action != 'build': parser.error('--output is only valid with build')
    root = args.root.resolve()
    try:
        if args.action == 'build':
            path, record = build(root, args.output)
            result = {'status':'PASS','action':'build','path':str(path),'fingerprint':record['fingerprint'],'skills':len(load_manifest(root)),'files':len(record['files'])}
        else:
            payload = sync(root) if args.action == 'sync' else check(root)
            result = {'status':'PASS','action':args.action,'skills':len(payload),'files':sum(map(len,payload.values())),'sharedCopies':sum(len(e['shared']) for e in load_manifest(root))}
        print(json.dumps(result, ensure_ascii=False));return 0
    except (PackageError, OSError, ValueError, KeyError, TypeError, UnicodeError) as exc:
        print(json.dumps({'status':'FAIL','action':args.action,'error':str(exc)},ensure_ascii=False),file=sys.stderr);return 1

if __name__ == '__main__':
    raise SystemExit(main())
